#!/usr/bin/env python3
"""UI strings: Chinese in the source, English from Resources/en.json.

  scripts/i18n.py wrap <files...>   wrap Chinese string literals in L("...")
  scripts/i18n.py check             list L("...") keys missing from en.json
  scripts/i18n.py gen               write Sources/KolibriCore/Strings+en.swift from en.json

Keys are the Chinese literal with each interpolation replaced by {} (L() matches the
final string against these templates at runtime)."""
import json, re, sys
from pathlib import Path

HAN = re.compile(r"[一-鿿]")
ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "Resources/en.json"
GEN = ROOT / "Sources/KolibriCore/Strings+en.swift"
RAW_CASE = re.compile(r"\bcase\s+\w+\s*=\s*$")   # enum raw values must stay literals


def parse_string(src, i):
    """src[i] == '"'. Returns (end_index_after_literal, own_text_with_{} , [(start,end) of interpolations])."""
    assert src[i] == '"'
    j = i + 1
    own = []
    interps = []
    while j < len(src):
        c = src[j]
        if c == "\\" and j + 1 < len(src) and src[j + 1] == "(":
            k = j + 2
            depth = 1
            start = k
            while depth:
                ch = src[k]
                if ch == '"':
                    k = parse_string(src, k)[0]
                    continue
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                k += 1
            interps.append((start, k - 1))
            own.append("{}")
            j = k
            continue
        if c == "\\":
            own.append(src[j:j + 2])
            j += 2
            continue
        if c == '"':
            return j + 1, "".join(own), interps
        own.append(c)
        j += 1
    raise ValueError("unterminated string")


def rewrite(src, keys):
    out = []
    i = 0
    n = len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            e = src.find("\n", i)
            e = n if e < 0 else e
            out.append(src[i:e]); i = e; continue
        if src.startswith("/*", i):
            e = src.find("*/", i) + 2
            out.append(src[i:e]); i = e; continue
        if src.startswith('"""', i):
            e = src.find('"""', i + 3) + 3
            out.append(src[i:e]); i = e; continue
        if c == '"':
            end, own, interps = parse_string(src, i)
            # Rewrite inside interpolations first (nested literals).
            lit = []
            pos = i
            for (a, b) in interps:
                lit.append(src[pos:a]); lit.append(rewrite(src[a:b], keys)); pos = b
            lit.append(src[pos:end])
            literal = "".join(lit)
            before = "".join(out)[-80:]
            wrapped = HAN.search(own) and not before.rstrip().endswith("L(") and not RAW_CASE.search(before)
            if wrapped:
                keys.add(bytes(own, "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8") if "\\" in own else own)
                literal = f"L({literal})"
            out.append(literal)
            i = end
            continue
        out.append(c)
        i += 1
    return "".join(out)


def main():
    cmd = sys.argv[1]
    if cmd == "wrap":
        keys = set()
        for f in sys.argv[2:]:
            p = Path(f)
            s = p.read_text()
            t = rewrite(s, keys)
            if t != s:
                p.write_text(t)
                print("wrapped", f)
        print(len(keys), "keys")
    elif cmd == "gen":
        table = json.loads(TABLE.read_text())
        def lit(x):
            return '"' + x.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
        lines = [f"    {lit(k)}: {lit(v)}," for k, v in sorted(table.items()) if v]
        GEN.write_text("// Generated by scripts/i18n.py gen from Resources/en.json. Do not edit.\n\n"
                       "let englishStrings: [String: String] = [\n" + "\n".join(lines) + "\n]\n")
        print(f"wrote {GEN.name}: {len(lines)} strings")
    elif cmd == "check":
        keys = set()
        for p in (ROOT / "Sources").rglob("*.swift"):
            s = p.read_text()
            for m in re.finditer(r'L\("', s):
                _, own, _ = parse_string(s, m.end() - 1)
                if HAN.search(own):
                    keys.add(own.replace('\\"', '"').replace("\\n", "\n"))
        table = json.loads(TABLE.read_text()) if TABLE.exists() else {}
        missing = sorted(k for k in keys if k not in table)
        json.dump({k: "" for k in missing}, sys.stdout, ensure_ascii=False, indent=1)
        print(f"\n{len(missing)} missing of {len(keys)}", file=sys.stderr)


main()
