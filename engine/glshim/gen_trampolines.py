#!/usr/bin/env python3
"""Generate arm64 forwarding trampolines for the Kolibri GLES shim.

Every exported function of the shim jumps (tail call, registers untouched) to the
real ANGLE implementation, whose address is filled into a table at load time.
This needs no function signatures and no dyld re-exports.

usage: gen_trampolines.py <out.s> <out_table.c> <prefix> <skip,names> NAME[=IMPL] ...
  NAME is the exported symbol, IMPL the symbol looked up in the real library
  (defaults to NAME).
"""
import os
import sys


def main() -> None:
    out_s, out_c, prefix, skip = sys.argv[1:5]
    skip_set = {s for s in skip.split(",") if s}
    pairs = []
    for arg in sys.argv[5:]:
        name, _, impl = arg.partition("=")
        if name not in skip_set:
            pairs.append((name, impl or name))
    tab = f"{prefix}_tab"
    trace = os.environ.get("GLSHIM_TRACE") == "1"
    with open(out_s, "w") as f:
        f.write(".text\n.p2align 2\n")
        for i, (name, _) in enumerate(pairs):
            # Scaled 12-bit immediate: up to 4095 entries per table.
            assert i < 4096
            f.write(f".globl _{name}\n_{name}:\n")
            if trace:
                # Count the call: save every argument register (x0-x8, q0-q7) around the C hook.
                f.write(
                    "  stp x29, x30, [sp, #-224]!\n  mov x29, sp\n"
                    "  stp x0, x1, [sp, #16]\n  stp x2, x3, [sp, #32]\n  stp x4, x5, [sp, #48]\n"
                    "  stp x6, x7, [sp, #64]\n  str x8, [sp, #80]\n"
                    "  stp q0, q1, [sp, #96]\n  stp q2, q3, [sp, #128]\n  stp q4, q5, [sp, #160]\n  stp q6, q7, [sp, #192]\n"
                    f"  mov x0, #{i}\n  bl _{prefix}_count_call\n"
                    "  ldp x0, x1, [sp, #16]\n  ldp x2, x3, [sp, #32]\n  ldp x4, x5, [sp, #48]\n"
                    "  ldp x6, x7, [sp, #64]\n  ldr x8, [sp, #80]\n"
                    "  ldp q0, q1, [sp, #96]\n  ldp q2, q3, [sp, #128]\n  ldp q4, q5, [sp, #160]\n  ldp q6, q7, [sp, #192]\n"
                    "  ldp x29, x30, [sp], #224\n"
                )
            f.write(
                f"  adrp x16, _{tab}@PAGE\n"
                f"  add x16, x16, _{tab}@PAGEOFF\n"
                f"  ldr x16, [x16, #{8 * i}]\n"
                f"  br x16\n"
            )
    with open(out_c, "w") as f:
        f.write("// Generated by gen_trampolines.py\n")
        f.write(f"void* {tab}[{max(len(pairs), 1)}] __attribute__((visibility(\"hidden\")));\n")
        f.write(f"const char* const {prefix}_names[] __attribute__((visibility(\"hidden\"))) = {{\n")
        for _, impl in pairs:
            f.write(f'    "{impl}",\n')
        f.write("};\n")
        f.write(f"const int {prefix}_count __attribute__((visibility(\"hidden\"))) = {len(pairs)};\n")


if __name__ == "__main__":
    main()
